@pytest.fixture(scope="module")
def produced(tmp_path_factory: pytest.TempPathFactory) -> Path:
    return produce(REFERENCE, tmp_path_factory.mktemp("reference")).output_dir


def day_file(output: Path, day: date, suffix: str) -> Path:
    return output / "exports" / "daily" / f"{day.year}" / f"{day.month:02d}" / f"{day}.{suffix}"


def _jsonl_rows(output: Path, day: date) -> list[dict[str, object]]:
    text = day_file(output, day, "jsonl").read_text(encoding="utf-8")
    return [json.loads(line) for line in text.splitlines()]


def test_daily_file_paths_are_unchanged(produced: Path) -> None:
    for day in (NORMAL_DAY, DST_DAY):
        for suffix in ("jsonl", "csv", "parquet", "manifest.json"):
            expected = produced / "exports" / "daily" / "2026" / "10" / f"{day}.{suffix}"
            assert expected.is_file(), f"missing {expected}"
    assert (produced / "metadata" / "export_runs.jsonl").is_file()


@pytest.mark.parametrize(
    ("day", "suffix", "expected"),
    [
        (date(2026, 1, 5), "jsonl", "exports/daily/2026/01/2026-01-05.jsonl"),
        (date(2026, 9, 30), "csv", "exports/daily/2026/09/2026-09-30.csv"),
        (date(2026, 10, 24), "parquet", "exports/daily/2026/10/2026-10-24.parquet"),
        (date(2027, 12, 31), "manifest.json", "exports/daily/2027/12/2027-12-31.manifest.json"),
    ],
)
def test_day_file_paths_are_zero_padded(
    tmp_path: Path, day: date, suffix: str, expected: str
) -> None:
    cfg = make_config(tmp_path)
    path = day_path(cfg, day, suffix)
    assert path.relative_to(Path(cfg.export.output_dir)).as_posix() == expected


def test_manifest_field_order_matches_schema_1_4(produced: Path) -> None:
    manifest = json.loads(day_file(produced, NORMAL_DAY, "manifest.json").read_text("utf-8"))
    assert list(manifest) == MANIFEST_FIELDS
    assert manifest["schema_version"] == "1.4"
    assert manifest["source"] == "home_assistant_rest_history"
    assert manifest["status"] == "ok"
    assert list(manifest["output_files"]) == ["jsonl", "csv", "parquet"]
    assert list(manifest["artifacts"]) == ["jsonl", "csv", "parquet"]
    assert list(manifest["artifacts"]["jsonl"]) == [
        "filename",
        "size_bytes",
        "sha256",
        "row_count",
        "logical_sha256",
    ]
    assert list(manifest["history_request_options"]) == [
        "minimal_response",
        "no_attributes",
        "significant_changes_only",
        "skip_initial_state",
    ]


def test_run_log_field_order_is_unchanged(produced: Path) -> None:
    lines = (produced / "metadata" / "export_runs.jsonl").read_text("utf-8").splitlines()
    assert [json.loads(line)["day"] for line in lines] == [str(NORMAL_DAY), str(DST_DAY)]
    for line in lines:
        assert list(json.loads(line)) == RUN_LOG_FIELDS


def test_jsonl_row_shape_is_unchanged(produced: Path) -> None:
    rows = _jsonl_rows(produced, NORMAL_DAY)
    for row in rows:
        assert list(row) == JSONL_FIELDS
    assert str(rows[0]["last_changed"]).endswith("+00:00")
    assert rows[0]["local_offset"] == "+02:00"


def test_json_outputs_end_every_line_with_lf_only(produced: Path) -> None:
    jsonl = day_file(produced, NORMAL_DAY, "jsonl").read_bytes()
    assert jsonl.endswith(b"\n")
    assert jsonl.count(b"\n") == 5
    for path in (
        day_file(produced, NORMAL_DAY, "jsonl"),
        day_file(produced, NORMAL_DAY, "manifest.json"),
        produced / "metadata" / "export_runs.jsonl",
    ):
        assert b"\r" not in path.read_bytes(), path.name


def test_csv_header_and_line_terminator_are_unchanged(produced: Path) -> None:
    raw = day_file(produced, NORMAL_DAY, "csv").read_bytes()
    header, _, rest = raw.partition(b"\r\n")
    assert header.decode("utf-8").split(",") == CSV_HEADER
    assert rest.endswith(b"\r\n")


def test_local_offset_follows_the_dst_change_within_one_file(produced: Path) -> None:
    offsets = {row["last_changed"]: row["local_offset"] for row in _jsonl_rows(produced, DST_DAY)}
    assert offsets["2026-10-24T23:30:00+00:00"] == "+02:00"
    assert offsets["2026-10-25T00:59:59+00:00"] == "+01:00"
    assert offsets["2026-10-25T01:00:00+00:00"] == "+01:00"
    assert offsets["2026-10-25T01:30:00+00:00"] == "+01:00"


def test_local_offset_is_derived_from_last_updated(produced: Path) -> None:
    rows = _jsonl_rows(produced, DST_DAY)
    straddling = next(row for row in rows if row["entity_id"] == "binary_sensor.front_door")
    assert straddling["last_changed"] == "2026-10-25T00:59:59+00:00"
    assert straddling["last_updated"] == "2026-10-25T01:00:01+00:00"
    assert straddling["local_offset"] == "+01:00"


def test_the_dst_day_spans_twenty_five_hours(produced: Path) -> None:
    manifest = json.loads(day_file(produced, DST_DAY, "manifest.json").read_text("utf-8"))
    start = datetime.fromisoformat(manifest["start_utc"])
    end = datetime.fromisoformat(manifest["end_utc"])
    assert (end - start).total_seconds() == 25 * 3600


def test_entities_without_history_are_recorded_not_failed(produced: Path) -> None:
    normal = json.loads(day_file(produced, NORMAL_DAY, "manifest.json").read_text("utf-8"))
    dst = json.loads(day_file(produced, DST_DAY, "manifest.json").read_text("utf-8"))
    assert normal["zero_history_entities"] == ["sensor.never_recorded"]
    assert dst["zero_history_entities"] == ["sensor.never_recorded", "sensor.status_note"]
    assert normal["failed_batches"] == [] and dst["failed_batches"] == []
    assert normal["entity_count_current"] == REFERENCE.entity_count_total
    assert normal["entity_count_requested"] == len(REFERENCE_ENTITY_IDS)
